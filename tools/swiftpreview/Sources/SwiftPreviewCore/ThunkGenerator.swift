import Foundation

/// The outcome of planning a hot reload for one file.
public enum ThunkPlan: Equatable {
  /// Swift source for the thunk file.
  case thunk(String)
  /// The change touches layout (stored properties, inits, conformances, …):
  /// the module has to be rebuilt by Bazel.
  case needsRebuild(reason: String)
}

public struct ThunkOptions: Sendable {
  public var moduleName: String
  /// Name of the runtime module linked into the host.
  public var runtimeModule: String = "SwiftPreviewRuntime"
  /// Emit preview registration for this file's `#Preview`s.
  public var registerPreviews: Bool
  /// Identifies the file to the runtime registry.
  public var fileKey: String

  public init(moduleName: String, registerPreviews: Bool, fileKey: String) {
    self.moduleName = moduleName
    self.registerPreviews = registerPreviews
    self.fileKey = fileKey
  }
}

public enum ThunkGenerator {
  /// Plans a thunk for `current`, given the file as it was at the last full
  /// build (`baseline`). Members whose signature exists in the baseline become
  /// `@_dynamicReplacement`s; new members and new types are compiled into the
  /// thunk as plain declarations.
  public static func plan(current: FileAnalysis, baseline: FileAnalysis, options: ThunkOptions) -> ThunkPlan {
    if Set(current.otherTopLevel) != Set(baseline.otherTopLevel) {
      return .needsRebuild(reason: "a top-level declaration changed in \(basename(current.path))")
    }

    var baselineScopes: [String: [TypeScope]] = [:]
    for scope in baseline.scopes { baselineScopes[key(scope), default: []].append(scope) }
    var seen: [String: Int] = [:]
    let baselinePaths = Set(baseline.scopes.map(\.path))

    var out: [String] = []
    out.append("// Generated by swiftpreview for \(current.path). Do not edit.")
    out.append("@_private(sourceFile: \"\(escape(basename(current.path)))\") import \(options.moduleName)")
    for imp in current.imports {
      if let name = importedModule(imp), name == options.moduleName { continue }
      out.append(stripImportAttributes(imp))
    }
    if options.registerPreviews {
      out.append("import SwiftUI")
      out.append("import \(options.runtimeModule)")
    }
    out.append("")

    for scope in current.scopes {
      let k = key(scope)
      let n = seen[k, default: 0]
      seen[k] = n + 1
      let base = baselineScopes[k].flatMap { n < $0.count ? $0[n] : nil }

      if scope.kind == "protocol" {
        if let base, base.layout == scope.layout { continue }
        if base != nil { return .needsRebuild(reason: "protocol \(scope.path) changed") }
        out.append(wrap(located(scope.verbatim, file: current.path, line: scope.line), scope.conditions))
        continue
      }

      guard let base else {
        // A scope with no counterpart in the last build.
        if scope.kind == "extension" {
          if !scope.layout.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .needsRebuild(reason: "new extension of \(scope.path) with conformances or stored members")
          }
          // Members of a new plain extension compile into the thunk as-is.
          out.append(wrap(located(scope.verbatim, file: current.path, line: scope.line), scope.conditions))
          continue
        }
        if let parent = scope.parentPath, baselinePaths.contains(parent) || current.scopes.contains(where: { $0.path == parent && $0.kind != "extension" }) {
          // A new nested type: only top-level-new types are emitted verbatim
          // (their nested types come along), so emit when the parent existed.
          if baselinePaths.contains(parent) {
            out.append(wrap("extension \(parent) {\n\(located(scope.verbatim, file: current.path, line: scope.line))\n}", scope.conditions))
          }
          continue
        }
        if scope.parentPath == nil {
          out.append(wrap(located(scope.verbatim, file: current.path, line: scope.line), scope.conditions))
        }
        continue
      }

      if base.layout != scope.layout {
        return .needsRebuild(reason: "the stored layout of \(scope.path) changed (stored properties, initializers, cases or conformances)")
      }
      let baseSignatures = Set(base.members.map(\.signature))
      var body: [String] = []
      for member in scope.members {
        if baseSignatures.contains(member.signature) {
          body.append(member.replacement)
        } else {
          if member.verbatim.contains("override ") {
            return .needsRebuild(reason: "new override in \(scope.path)")
          }
          body.append(member.verbatim)
        }
      }
      if body.isEmpty { continue }
      let whereClause = scope.whereClause.isEmpty ? "" : " " + scope.whereClause
      out.append(wrap("extension \(scope.path)\(whereClause) {\n\(body.joined(separator: "\n\n"))\n}", scope.conditions))
    }

    let baseGlobals = Set(baseline.globals.map(\.signature))
    for g in current.globals {
      out.append(baseGlobals.contains(g.signature) ? g.replacement : g.verbatim)
    }

    if options.registerPreviews {
      out.append(registration(current.previews, options: options))
    }
    return .thunk(out.joined(separator: "\n") + "\n")
  }

  // MARK: Preview registration

  static func registration(_ previews: [PreviewDecl], options: ThunkOptions) -> String {
    let rt = options.runtimeModule
    var decls: [String] = []
    var appends: [String] = []
    for p in previews {
      let name = escape(p.displayName)
      let layout: String
      switch p.layout {
      case .device: layout = ".device"
      case .sizeThatFits: layout = ".sizeThatFits"
      case .fixed(let w, let h): layout = ".fixed(width: \(w), height: \(h))"
      }
      let make: String
      switch p.kind {
      case .provider:
        make = "{ AnyView(\(p.providerType!).previews) }"
      case .macro where !p.previewables.isEmpty:
        decls.append(wrap("""
          private struct __SwiftPreview_\(p.index): View {
          \(p.previewables.map { "  " + $0 }.joined(separator: "\n"))
            var body: some View {
          \(p.body)
            }
          }
          """, p.conditions))
        make = "{ AnyView(__SwiftPreview_\(p.index)()) }"
      case .macro:
        decls.append(wrap("""
          @MainActor private func __swiftpreview_make_\(p.index)() -> AnyView {
            \(rt).PreviewContent.make {
          \(p.body)
            }
          }
          """, p.conditions))
        make = "{ __swiftpreview_make_\(p.index)() }"
      }
      appends.append(wrap("entries.append(\(rt).PreviewEntry(name: \"\(name)\", line: \(p.line), layout: \(layout), make: \(make)))", p.conditions))
    }
    return """

      // MARK: Previews
      \(decls.joined(separator: "\n\n"))

      @_cdecl("swiftpreview_register")
      public func __swiftpreview_register() {
        MainActor.assumeIsolated {
          var entries: [\(rt).PreviewEntry] = []
      \(appends.joined(separator: "\n"))
          \(rt).PreviewRegistry.set(file: "\(escape(options.fileKey))", entries)
        }
      }
      """
  }

  // MARK: Helpers

  static func key(_ scope: TypeScope) -> String {
    scope.conditions.joined(separator: "&&") + "|" + scope.kind + " " + scope.path + " " + scope.whereClause
  }

  static func wrap(_ text: String, _ conditions: [String]) -> String {
    var result = text
    for cond in conditions.reversed() {
      result = "#if \(cond)\n\(result)\n#endif"
    }
    return result
  }

  static func located(_ text: String, file: String, line: Int) -> String {
    guard line > 0 else { return text }
    return "#sourceLocation(file: \"\(escape(file))\", line: \(line))\n\(text)\n#sourceLocation()"
  }

  static func escape(_ s: String) -> String {
    s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
  }

  static func basename(_ path: String) -> String {
    (path as NSString).lastPathComponent
  }

  static func importedModule(_ imp: String) -> String? {
    let tokens = imp.split(whereSeparator: { $0 == " " || $0 == "\n" })
    guard let i = tokens.firstIndex(of: "import"), i + 1 < tokens.count else { return nil }
    var next = i + 1
    if ["struct", "class", "enum", "protocol", "typealias", "func", "var", "let"].contains(String(tokens[next])), next + 1 < tokens.count {
      next += 1
    }
    return tokens[next].split(separator: ".").first.map(String.init)
  }

  /// `@testable import X` needs X built for testing; `@_private` (on the
  /// module under preview) already gives the access a thunk needs.
  static func stripImportAttributes(_ imp: String) -> String {
    var s = imp
    for attr in ["@testable ", "@_implementationOnly ", "@_exported "] {
      s = s.replacingOccurrences(of: attr, with: "")
    }
    return s
  }
}
